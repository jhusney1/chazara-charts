#!/usr/bin/env node
/**
 * Regenerates data/perakimData.js from Sefaria.
 *
 *   node scripts/fetch-perakim.mjs
 *
 * For each tractate in data/tractateData.js this reads Sefaria's index
 * (the "Chapters" alternate structure of the Bavli text), which lists every
 * perek with its number, English and Hebrew name and the daf it starts on.
 * The output is committed so the server never needs network access.
 */

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tractateData = require(join(root, 'data', 'tractateData.js'));

// Our tractate names -> Sefaria index titles where they differ.
const SEFARIA_TITLES = {
  Berachot: 'Berakhot',
  Bechorot: 'Bekhorot',
  Arachin: 'Arakhin'
};

// Middot and Kinnim are Mishnah only: Sefaria has no daf layout for them, so
// they get no perek rows.
const OVERRIDES = {
  Middot: [],
  Kinnim: []
};

// Shekalim is Yerushalmi, printed in the Bavli with its own pagination.
// Sefaria's "Daf Yomi" structure lists those dapim with the Yerushalmi
// chapter each starts in, which gives the perek boundaries; the perek names
// come from the Mishnah since the Yerushalmi index does not carry them.
const SHEKALIM_NAMES = [
  ["Be'echad Be'Adar", 'באחד באדר'],
  ['Metzarfin Shekalim', 'מצרפין שקלים'],
  ['BiShloshah Perakim', 'בשלשה פרקים'],
  ['HaTerumah', 'התרומה'],
  ['Eilu Hein HaMemunin', 'אלו הן הממונין'],
  ['Shloshah Asar Shofarot', 'שלשה עשר שופרות'],
  ["Maot SheNimtze'u", 'מעות שנמצאו'],
  ['Kol HaRukin', 'כל הרוקין']
];

async function fetchShekalim() {
  const response = await fetch('https://www.sefaria.org/api/v2/index/Jerusalem%20Talmud%20Shekalim');
  if (!response.ok) throw new Error(`Shekalim: Sefaria returned ${response.status}`);
  const index = await response.json();
  const node = index?.alts?.['Daf Yomi'];
  if (!node?.refs) throw new Error('Shekalim: no Daf Yomi structure in Sefaria index');

  // refs[i] covers the i-th amud counting from `offset` (2a, 2b, 3a, ...)
  // and reads "Jerusalem Talmud Shekalim <chapter>:<halakhah>:<segment>-...".
  const offset = node.offset || 2;
  const perakim = [];
  node.refs.forEach((ref, index) => {
    const match = ref.match(/Shekalim (\d+):/);
    if (!match) return;
    const chapter = Number(match[1]);
    if (perakim.some((p) => p.number === chapter)) return;
    const [name, heName] = SHEKALIM_NAMES[chapter - 1] || [`Chapter ${chapter}`, `פרק ${chapter}`];
    perakim.push({
      number: chapter,
      name,
      heName,
      daf: offset + Math.floor(index / 2),
      amud: index % 2 === 0 ? 'a' : 'b'
    });
  });
  return perakim;
}

/**
 * "Berakhot 13a:16-17b:11" -> { daf: 13, amud: 'a' }
 */
function startOf(wholeRef) {
  const match = wholeRef.match(/\s(\d+)([ab])(?::\d+)?-/);
  if (!match) throw new Error(`Cannot read starting daf from "${wholeRef}"`);
  return { daf: Number(match[1]), amud: match[2] };
}

/**
 * "Chapter 1; MeEimatai" -> "MeEimatai"
 */
function englishName(title) {
  const parts = title.split(';');
  return (parts[1] || parts[0]).trim();
}

async function fetchPerakim(tractate) {
  if (OVERRIDES[tractate]) return OVERRIDES[tractate];
  if (tractate === 'Shekalim') return fetchShekalim();

  const title = SEFARIA_TITLES[tractate] || tractate;
  const response = await fetch(`https://www.sefaria.org/api/v2/index/${encodeURIComponent(title)}`);
  if (!response.ok) throw new Error(`${tractate}: Sefaria returned ${response.status} for "${title}"`);

  const index = await response.json();
  const nodes = index?.alts?.Chapters?.nodes;
  if (!nodes) throw new Error(`${tractate}: no Chapters structure in Sefaria index "${title}"`);

  return nodes.map((node) => ({
    number: node.numeric_equivalent,
    name: englishName(node.title),
    heName: node.heTitle,
    ...startOf(node.wholeRef)
  }));
}

const result = {};
for (const tractate of Object.keys(tractateData)) {
  result[tractate] = await fetchPerakim(tractate);
  console.log(`${tractate}: ${result[tractate].length} perakim`);
}

const body = Object.entries(result)
  .map(([tractate, perakim]) => {
    const rows = perakim
      .map((p) => `    { number: ${p.number}, name: ${JSON.stringify(p.name)}, heName: ${JSON.stringify(p.heName)}, daf: ${p.daf}, amud: '${p.amud}' }`)
      .join(',\n');
    return `  ${JSON.stringify(tractate)}: [${rows ? `\n${rows}\n  ` : ''}]`;
  })
  .join(',\n');

const file = `/**
 * Perek boundaries for every tractate: number, English and Hebrew name, and
 * the daf/amud the perek begins on.
 *
 * GENERATED by scripts/fetch-perakim.mjs from Sefaria on ${new Date().toISOString().slice(0, 10)}.
 * Do not edit by hand; re-run the script instead.
 */
const perakimData = {
${body}
};

module.exports = perakimData;
`;

writeFileSync(join(root, 'data', 'perakimData.js'), file);
console.log('wrote data/perakimData.js');
