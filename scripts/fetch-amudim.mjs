#!/usr/bin/env node
/**
 * Regenerates client/src/components/charts/data/mishnaBeruraAmudim.js.
 *
 *   node scripts/fetch-amudim.mjs
 *
 * The Mishna Berura Amud Yomi program (mishnaberurayomi.org, the Chicago
 * Center) publishes one written digest and one recorded shiur per amud, in a
 * folder per chelek. Each file is named for the amud and the text it covers:
 *
 *   pdf_digest/Chelek_2/0327_Siman_143_Seif_4a.pdf
 *   mp3_shiurim/Chelek_2/0327_Siman_143_Seif_4a.mp3
 *
 * so the directory listings are an amud -> siman/se'if table for the whole
 * Mishna Berura. This reads both listings, takes the written digests as the
 * primary source and the shiurim to fill the few amudim with no digest, and
 * records where each amud starts and which chelek folder it sits in. The
 * output is committed so neither the server nor the client needs the network.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(root, 'client', 'src', 'components', 'charts', 'data', 'mishnaBeruraAmudim.js');
const BASE = 'https://mishnaberurayomi.org';
const CHALAKIM = [1, 2, 3, 4, 5, 6];
const SOURCES = [
  { folder: 'pdf_digest', ext: 'pdf' },
  { folder: 'mp3_shiurim', ext: 'mp3' }
];

async function listing(folder, chelek, ext) {
  const url = `${BASE}/${folder}/Chelek_${chelek}/`;
  const response = await fetch(url, { headers: { 'User-Agent': 'chazara-charts data script' } });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const html = await response.text();
  const pattern = new RegExp(`href="(\\d{4}_[^"]+?)\\.${ext}"`, 'g');
  return [...html.matchAll(pattern)].map((match) => decodeURIComponent(match[1]));
}

/**
 * The amud number and the first siman/se'if a file name covers. Names vary
 * ("Seif"/"seif", "Siman%20_547", a trailing ".pdf"), but every one starts
 * with the amud number and its first siman and se'if. A letter after the
 * se'if ("4a", "4b") marks a se'if split across amudim; only the number is
 * kept. A review amud ("0637_Siman_259_Seif_review") has no se'if: it goes
 * back over the siman just finished.
 */
function parseName(name) {
  const match = name.match(/^(\d{4})_Siman\s*_?(\d+)_[Ss]eif_(\d+|review)/);
  if (!match) return null;
  const seif = match[3] === 'review' ? null : Number(match[3]);
  return { amud: Number(match[1]), siman: Number(match[2]), seif };
}

// A review amud sorts after every se'if of its siman.
const seifOrder = (entry) => (entry.seif === null ? Infinity : entry.seif);
const compareStart = (a, b) => a.siman - b.siman || seifOrder(a) - seifOrder(b);

const bySource = SOURCES.map(() => new Map());
for (const [index, { folder, ext }] of SOURCES.entries()) {
  for (const chelek of CHALAKIM) {
    for (const name of await listing(folder, chelek, ext)) {
      const parsed = parseName(name);
      if (!parsed) throw new Error(`Unrecognised file name: ${folder}/Chelek_${chelek}/${name}`);
      const entries = bySource[index].get(parsed.amud) || [];
      entries.push({ ...parsed, chelek });
      bySource[index].set(parsed.amud, entries);
    }
  }
}

const lastAmud = Math.max(...bySource.flatMap((source) => [...source.keys()]));
const amudim = [];
for (let amud = 1; amud <= lastAmud; amud++) {
  // A few amudim have two digests (re-recorded or split); the amud starts
  // where the earliest of them does.
  const candidates = bySource.map((source) => source.get(amud)).find(Boolean);
  if (!candidates) throw new Error(`No file in any listing for amud ${amud}`);
  amudim.push(candidates.slice().sort(compareStart)[0]);
}

// The listings must read as one continuous pass through the sefer.
amudim.forEach((entry, index) => {
  const previous = amudim[index - 1];
  if (previous && compareStart(entry, previous) < 0) {
    throw new Error(`Amud ${entry.amud} (${entry.siman}:${entry.seif}) starts before amud ${previous.amud}`);
  }
  if (previous && entry.chelek < previous.chelek) {
    throw new Error(`Amud ${entry.amud} is filed in an earlier chelek than amud ${previous.amud}`);
  }
});

const chalakim = CHALAKIM.map((chelek) => {
  const inChelek = amudim.filter((entry) => entry.chelek === chelek);
  return { chelek: `Chelek ${chelek}`, start: inChelek[0].amud, end: inChelek[inChelek.length - 1].amud };
});

const starts = amudim.map(({ siman, seif }) => (seif === null ? `${siman}` : `${siman}:${seif}`));
const lines = [];
for (let i = 0; i < starts.length; i += 20) lines.push(`  '${starts.slice(i, i + 20).join(' ')}'`);
const chelekLines = chalakim.map(({ chelek, start, end }) => `  { chelek: '${chelek}', start: ${start}, end: ${end} }`);

const source = `/**
 * Mishna Berura Amud Yomi: where each amud of the daily cycle starts.
 *
 * GENERATED by scripts/fetch-amudim.mjs from the per-amud file listings of
 * the Mishna Berura Amud Yomi program (mishnaberurayomi.org). Do not edit by
 * hand; rerun the script.
 *
 * Amudim are numbered 1-${lastAmud} straight through the six chalakim, as the
 * program numbers them. AMUD_STARTS[n - 1] is the siman:se'if amud n opens
 * with; an amud runs until the next one starts. A bare siman (no se'if) is a
 * review amud for that siman.
 */

const AMUD_STARTS = [
${lines.join(',\n')}
]
  .join(' ')
  .split(' ');

/** The amudim filed under each chelek by the program. */
export const amudChalakim = [
${chelekLines.join(',\n')}
];

export const AMUD_COUNT = AMUD_STARTS.length;

/**
 * Details of one amud, or null outside 1-AMUD_COUNT.
 * @returns {{ amud: number, siman: number, seif: number | null, chelek: string } | null}
 */
export function amudInfo(amud) {
  const n = Number(amud);
  if (!Number.isInteger(n) || n < 1 || n > AMUD_STARTS.length) return null;
  const [siman, seif] = AMUD_STARTS[n - 1].split(':');
  const { chelek } = amudChalakim.find((c) => n >= c.start && n <= c.end);
  return { amud: n, siman: Number(siman), seif: seif === undefined ? null : Number(seif), chelek };
}

/** Where an amud starts, as "siman:se'if" (or the bare siman for a review amud). */
export function amudStart(amud) {
  const info = amudInfo(amud);
  if (!info) return '';
  return info.seif === null ? \`\${info.siman}\` : \`\${info.siman}:\${info.seif}\`;
}

/** Row label for a chart: amud number, then where it starts. */
export function amudLabel(amud) {
  const info = amudInfo(amud);
  return info ? \`\${info.amud} · \${amudStart(amud)}\` : String(amud);
}
`;

writeFileSync(OUTPUT, source);
console.log(`Wrote ${amudim.length} amudim (${chalakim.map((c) => `${c.chelek} ${c.start}-${c.end}`).join(', ')}) to ${OUTPUT}`);
